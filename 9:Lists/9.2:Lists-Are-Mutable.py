#Unlike strings, individual list elements can be changed.

#Example 1 – Change an Element
items = ["Sword", "Bow"]
items[0] = "Axe"
print(items)

#Output: ['Axe', 'Bow']


#Example 2 – Change Multiple Elements
weapons = ["Sword", "Bow", "Dagger"]
weapons[0] = "Axe"
weapons[2] = "Hammer"
print(weapons)

#Output: ['Axe', 'Bow', 'Hammer']