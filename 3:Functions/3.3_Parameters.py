#3.3_Parameters
#Example 1 – One Parameter
def greet(name):
    print("Hello", name)

greet("Krishna")

#Example 2 – Integer Parameter
def damage(amount):
    print("Damage:", amount)

damage(50)


#Example 3 – Multiple Parameters
def add(a, b):
    print(a + b)

add(10, 15)


#Example 4 – String Parameter
def weapon(name):
    print(name)

weapon("Sword")