# 10.7 Accumulating a List
# - Build list gradually with.append()


# Example 1: Loot system
loot = []
loot.append("Gold")
loot.append("Gem")
print(loot)
# Output: ['Gold', 'Gem']


# Example 2: Inventory build
inventory = []
inventory.append("Sword")
inventory.append("Potion")
print(inventory)
# Output: ['Sword', 'Potion']