# 10.1 Creating Dictionaries
# - Uses {} braces, Key -> Value mapping
# - Perfect for game entities

# Example 1: Player data
player = {
    "health": 100,
    "score": 500
}
print(player)
# Output: {'health': 100, 'score': 500}


# Example 2: Enemy data
enemy = {
    "name": "Dragon",
    "health": 500,
    "damage": 50
}
print(enemy)
# Output: {'name': 'Dragon', 'health': 500, 'damage': 50}


# Example 3: Weapon properties
weapon = {
    "name": "Sword",
    "damage": 25
}
print(weapon)
# Output: {'name': 'Sword', 'damage': 25}
