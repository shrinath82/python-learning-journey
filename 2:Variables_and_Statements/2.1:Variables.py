#Variables store values in memory.
#Example 1 – Store an Integer
age = 25
print(age)

#Example 2 – Store a String
name = "Alice"
print(name)

#Example 3 – Store a Float
price = 199.99
print(price)

#Example 4 – Store a Boolean
is_logged_in = True
print(is_logged_in)

#Example 5 – Changing a Variable
score = 50
print(score)
score = 80
print(score)

#Example 6 – Copying Variables
x = 100
y = x
print(x)
print(y)