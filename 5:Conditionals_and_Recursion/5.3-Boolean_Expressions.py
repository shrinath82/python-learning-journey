#5.3-Boolean_Expressions
#A Boolean expression evaluates to either `True` or `False`.
#Example 1 – Greater Than
print(5 > 3)

#Example 2 – Less Than
print(10 < 5)

#Example 3 – Equal To
print(10 == 10)

#Example 4 – Not Equal To
print(4 != 8)

#Example 5 – Greater Than or Equal To
score = 500
print(score >= 100)

#Example 6 – Less Than or Equal To
health = 0
print(health <= 0)