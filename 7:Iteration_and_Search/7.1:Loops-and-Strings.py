#A `for` loop can process a string one character at a time.
#Example 1 – Loop Through a String
for ch in "":
    print(ch)

#Example 2 – Loop Through a Variable
word = "dragon"
for letter in word:
    print(letter)

#Example 3 – User Input
name = input("Enter name: ")
for ch in name:
    print(ch)


